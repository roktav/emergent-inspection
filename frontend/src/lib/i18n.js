export const STATUS_CODES = ["OK", "NOT_OK", "KOROSI", "KURANG", "LONGGAR"];

const LangCtx = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => localStorage.getItem("dt_lang") || "en");
  const setLang = useCallback((l) => {
    localStorage.setItem("dt_lang", l);
    setLangState(l);
  }, []);
  const t = useCallback((k) => dict[lang]?.[k] ?? dict.en[k] ?? k, [lang]);
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <LangCtx.Provider value={value}>{children}</LangCtx.Provider>;
}

export const useT = () => useContext(LangCtx);
